print("Calculate the area of a wall.")

# Input & Conversion
Feed = input("Enter the width of the wall in meters: ")
Width = int(Feed)

Feed = input("Enter the height of the wall in meters: ")
Height = int(Feed)
# Print Width, Height & Area
print(f"Width is {Width} m and height is {Height} m.")

Area = Width * Height
print(f"The wall will be {Area} square meters.")
